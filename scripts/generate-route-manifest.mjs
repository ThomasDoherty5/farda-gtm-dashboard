// Generates src/routes/manifest.generated.ts from docs/figma-source-manifest.md.
// Source of truth: handoff section 6. Run: npm run manifest:generate
import { readFileSync, writeFileSync } from "node:fs";

const md = readFileSync(new URL("../docs/figma-source-manifest.md", import.meta.url), "utf8");
const rows = md.split("\n").filter((l) => l.startsWith("| [THO-"));
const entries = rows.map((line) => {
  const cells = line.split(" | ").map((c) => c.replace(/^\| ?| ?\|$/g, "").trim());
  const [ownerCell, screen, nodesCell, urlCell, scope] = cells;
  const owner = ownerCell.match(/THO-\d+/)[0];
  const nodes = [...nodesCell.matchAll(/\[(\d+:\d+)\]/g)].map((m) => m[1]);
  const rawUrl = urlCell.replace(/`/g, "");
  const m = rawUrl.match(/^([^\s?(]+)(\?[^\s(]+)?\s*(?:\((.+)\))?$/);
  if (!m || nodes.length !== 2) throw new Error(`Unparsed row: ${line}`);
  const query = m[2] ? Object.fromEntries(new URLSearchParams(m[2].slice(1))) : {};
  return { owner, screen, sourceNodeId: nodes[0], prototypeNodeId: nodes[1], path: m[1], query, variant: m[3] ?? null, scope };
});
const ids = new Set(entries.map((e) => e.sourceNodeId));
if (entries.length !== 60 || ids.size !== 60) throw new Error(`Expected 60 unique sources, got ${entries.length}/${ids.size}`);
const out = `// GENERATED by scripts/generate-route-manifest.mjs from docs/figma-source-manifest.md. Do not edit.
// Handoff revision: 2026-11-02. Figma file key: UkX7Vy6r5BGgYvUCAi6Pmd.
import type { SourceScreen } from "./types";

export const FIGMA_FILE_KEY = "UkX7Vy6r5BGgYvUCAi6Pmd";
export const sourceScreens: readonly SourceScreen[] = ${JSON.stringify(entries, null, 2)} as const;
`;
writeFileSync(new URL("../src/routes/manifest.generated.ts", import.meta.url), out);
console.log(`Wrote ${entries.length} source screens`);
