/** A source whose address alone doesn't pick it: the demo service keys the resolved return on a scenario. */
const EXTRA_QUERY: Record<string, Record<string, string>> = { "12:431": { scenario: "resolved" } };

export type CoverageRow = {
  owner: string;
  screen: string;
  sourceNodeId: string;
  prototypeNodeId: string;
  url: string;
  scope: string;
  variant: string | null;
  /** The width the design was drawn at. Only Operations has native 390 and 1024 designs. */
  designWidth: number;
  /** The fixture the comparison uses. FX-01 is the adapter's default demo dataset. */
  fixture: string;
};

/** Replaces each `:param` with the demo record id, and fails loudly when a parameterised source has no record. */
export function concreteUrl(source: SourceScreen): string {
  const params = RECORD_PARAMS[source.sourceNodeId] ?? {};
  const path = source.path.replace(/:(\w+)/g, (_m, name: string) => {
    const value = params[name];
    if (value === undefined) throw new Error(`No demo record for :${name} in source ${source.sourceNodeId}`);
    return value;
  });
  const query = new URLSearchParams({ ...source.query, ...(EXTRA_QUERY[source.sourceNodeId] ?? {}) }).toString();
  return query ? `${path}?${query}` : path;
}

const designWidthOf = (source: SourceScreen) => {
  const match = /^(\d+)px$/.exec(source.variant ?? "");
  return match ? Number(match[1]) : 1440;
};

export const coverageRows = (): CoverageRow[] =>
  sourceScreens.map((s) => ({
    owner: s.owner,
    screen: s.screen,
    sourceNodeId: s.sourceNodeId,
    prototypeNodeId: s.prototypeNodeId,
    url: concreteUrl(s),
    scope: s.scope,
    variant: s.variant,
    designWidth: designWidthOf(s),
    fixture: "FX-01",
  }));

/** One row per source screen. `built` is how the page rendered, as measured by the test, never typed in. */
export function renderCoverageDoc(rows: CoverageRow[], built: Record<string, boolean>, recorded: Record<string, boolean>): string {
  const lines = rows.map((r, i) => {
    const node = `[${r.sourceNodeId}](https://www.figma.com/design/${FIGMA_FILE_KEY}?node-id=${r.sourceNodeId.replace(":", "-")})`;
    return `| ${i + 1} | ${r.owner} | ${r.screen}${r.variant ? ` (${r.variant})` : ""} | ${node} | ${r.prototypeNodeId} | \`${r.url}\` | ${r.designWidth} | ${r.fixture} | ${built[r.sourceNodeId] ? "Built" : "Not built"} | ${recorded[r.sourceNodeId] ? "Recorded" : "Missing"} |`;
  });
  const unbuilt = rows.filter((r) => !built[r.sourceNodeId]).length;
  const missing = rows.filter((r) => !recorded[r.sourceNodeId]).length;
  return `# Screen coverage map

Generated by \`src/routes/screenCoverage.test.tsx\` from \`manifest.generated.ts\`. Do not edit by hand: run \`UPDATE_SCREEN_COVERAGE=1 npx vitest run src/routes/screenCoverage.test.tsx\` after the manifest, a route or \`docs/design-map.md\` changes. The test fails when this file is out of date.

${rows.length} source screens, ${rows.length - unbuilt} built, ${unbuilt} not built, ${missing} without a recorded comparison. The count comes from the manifest, not from a number typed here.

| Column | Meaning |
| -- | -- |
| Node | The source node, linked into the handoff's original file \`${FIGMA_FILE_KEY}\`. Comparisons were run against Thomas's copy \`z9knjMdQ3kxL6Fblvu1tKc\` (see \`figma-access-gap.md\`), because the original refuses MCP access. Implementation reads the source node, never the prototype clone |
| Prototype | The prototype clone, for interaction reference only |
| Demo URL | The route with the synthetic demo record the comparison uses. It rendered with a level-one heading when this file was generated |
| Design width | The width the design was drawn at. Only Operations has native 390 and 1024 designs |
| Fixture | FX-01, the adapter's default demo dataset. Other fixtures are read from \`?fixture=\` |
| Built | The route rendered the screen, not the "Not built yet" placeholder |
| Comparison | The source node appears in a measurement or difference table of \`docs/design-map.md\` |

| # | Owner | Screen | Node | Prototype | Demo URL | Design width | Fixture | Built | Comparison |
| -- | -- | -- | -- | -- | -- | -- | -- | -- | -- |
${lines.join("\n")}

## What this does not cover

- Alternate and overlay states (dialogs, drawers, filter menus). Each screen's dialogs are tested with that screen. Whether each prototype overlay is reachable is recorded separately by the prototype-edge checks, which are not part of this file.
- Whether the comparison passed. The numbers are in \`docs/design-map.md\`; this file only says one exists.
- Viewports other than the design width. Responsive checks are their own specs.
- Provider-backed behavior. The adapter is INTEGRATION_PENDING, so every row is fixture-complete at most.
`;
}
